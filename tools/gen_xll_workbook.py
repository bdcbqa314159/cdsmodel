#!/usr/bin/env python3
"""C8 of specs/03_xll.md -- a workbook that reports its own verdict.

An XLL only truly runs inside Excel, interactively, on Windows. That is a bad
oracle: "I opened it and it looked fine" is not evidence. So this writes a
workbook holding, for every case:

  * the inputs, as cells
  * BOTH registered forms of the formula
  * the value the C++ library computed, from the generator below
  * a verdict column comparing them

Excel recalculates on open and the sheet says PASS or FAIL per row. The person
with Excel reports what it said; they do not have to judge anything.

The expected values come from a small C++ program built against the same
library the add-in links, so this file never carries a hand-copied number.

    python tools/gen_xll_workbook.py            # writes tests/xll/smoke.xlsx
"""

from __future__ import annotations

import datetime as dt
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "xll" / "smoke.xlsx"

# Excel serial 1 is 1900-01-01; the Unix epoch is serial 25569. Pinned by a
# non-circular test in xl/core/tests/dispatch_test.cpp against serials read
# off Excel itself.
EXCEL_EPOCH = dt.date(1899, 12, 30)


def serial(d: dt.date) -> int:
    return (d - EXCEL_EPOCH).days


# One row per case. Kept small on purpose: this is a smoke test for the whole
# pipe, not a replacement for the 803 tests that already run without Excel.
CASES = [
    {
        "label": "5y, 100bp, ACT/360",
        "today": dt.date(2006, 10, 9),
        "start": dt.date(2006, 10, 9),
        "end": dt.date(2011, 10, 9),
        "coupon": 0.01,
        "recovery": 0.4,
        "clean": True,
    },
    {
        "label": "10y, 250bp",
        "today": dt.date(2006, 10, 9),
        "start": dt.date(2006, 10, 9),
        "end": dt.date(2016, 10, 9),
        "coupon": 0.025,
        "recovery": 0.4,
        "clean": True,
    },
    {
        # Valued MID-PERIOD, which is what makes the clean/dirty flag change
        # the answer. Two earlier attempts at this case returned the same
        # number for both: first with start == today (no accrual yet), then
        # with today on a quarterly coupon date (accrual resets to zero there).
        # The difference is now 37 days at 1% on ACT/360 = 0.001027778.
        "label": "5y mid-period, dirty",
        "today": dt.date(2006, 11, 15),
        "start": dt.date(2006, 7, 9),
        "end": dt.date(2011, 7, 9),
        "coupon": 0.01,
        "recovery": 0.4,
        "clean": False,
    },
    {
        "label": "5y mid-period, clean",
        "today": dt.date(2006, 11, 15),
        "start": dt.date(2006, 7, 9),
        "end": dt.date(2011, 7, 9),
        "coupon": 0.01,
        "recovery": 0.4,
        "clean": True,
    },
]

EXPECTED_SOURCE = r"""
// GENERATED by tools/gen_xll_workbook.py -- computes the expected values the
// workbook compares Excel against. Built against the same library the add-in
// links, so no number is ever hand-copied into the sheet.
#include <cdsmodel/cdsmodel.hpp>
#include <cstdio>
#include <span>
#include <vector>

using namespace cdsmodel;

int main() {
  const std::vector<Calendar> cals{Calendar::none()};
  const RatePoint disc_pts[]{{*make_date(2007, 1, 1), 0.04}, {*make_date(2030, 1, 1), 0.04}};
  const RatePoint sprd_pts[]{{*make_date(2007, 1, 1), 0.01}, {*make_date(2030, 1, 1), 0.01}};
  // One curve base date for every case, so a case's valuation date does not
  // silently change the curves it prices against.
  const Date curve_base = *make_date(2006, 10, 9);
  const Expected<ZeroCurve> discount =
      ZeroCurve::create(curve_base, disc_pts, kContinuousBasis, DayCount::Act365Fixed);
  const Expected<ZeroCurve> spread =
      ZeroCurve::create(curve_base, sprd_pts, kContinuousBasis, DayCount::Act365Fixed);
  if (!discount || !spread) {
    std::fprintf(stderr, "curves failed\n");
    return 1;
  }

  struct Case { int ty, tm, td; int ey, em, ed; double coupon; bool clean; };
  struct Start { int y, m, d; };
  const Start starts[]{{2006, 10, 9}, {2006, 10, 9}, {2006, 7, 9}, {2006, 7, 9}};
  // today, then end, then coupon and the clean flag.
  const Case cases[]{{2006, 10, 9, 2011, 10, 9, 0.01, true},
                     {2006, 10, 9, 2016, 10, 9, 0.025, true},
                     {2006, 11, 15, 2011, 7, 9, 0.01, false},
                     {2006, 11, 15, 2011, 7, 9, 0.01, true}};

  std::size_t index = 0;
  for (const Case &c : cases) {
    const Start &s = starts[index++];
    const Date today = *make_date(c.ty, c.tm, c.td);
    Cds cds;
    cds.start = *make_date(s.y, s.m, s.d);
    cds.end = *make_date(c.ey, c.em, c.ed);
    cds.coupon_rate = c.coupon;
    cds.day_count = DayCount::Act360;
    const Expected<double> price =
        cds_price(cds, today, today, today, std::span<const Calendar>{cals}, *discount,
                  *spread, 0.4, c.clean);
    if (!price) {
      std::printf("ERROR %s\n", price.error().message.c_str());
    } else {
      std::printf("%.12f\n", *price);
    }
  }
  return 0;
}
"""


def expected_values() -> list[str]:
    """Builds and runs the generator, returning one value per case."""
    compiler = shutil.which("c++") or shutil.which("cl")
    if compiler is None:
        sys.exit("no C++ compiler on PATH; cannot compute expected values")
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "expected.cpp"
        src.write_text(EXPECTED_SOURCE, encoding="utf-8")
        exe = Path(tmp) / "expected"
        build = subprocess.run(
            [compiler, "-std=c++20", f"-I{ROOT / 'include'}", str(src), "-o", str(exe)],
            capture_output=True, text=True,
        )
        if build.returncode != 0:
            sys.exit("could not build the expected-value generator:\n" + build.stderr[-1500:])
        run = subprocess.run([str(exe)], capture_output=True, text=True)
        if run.returncode != 0:
            sys.exit("the expected-value generator failed:\n" + run.stderr[-800:])
    values = [line.strip() for line in run.stdout.strip().split("\n") if line.strip()]
    if len(values) != len(CASES):
        sys.exit(f"expected {len(CASES)} values, got {len(values)}")
    return values


def main() -> int:
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Alignment, Font
    except ImportError:
        sys.exit("openpyxl is required: pip install openpyxl")

    values = expected_values()

    wb = Workbook()
    ws = wb.active
    ws.title = "Smoke"

    bold = Font(bold=True)
    ws["A1"] = "cdsmodel.xll smoke test"
    ws["A1"].font = Font(bold=True, size=14)
    ws["A2"] = (
        "Load cdsmodel.xll, then let this recalculate. The Verdict column "
        "compares Excel's answer against the C++ library's. Report what it says."
    )
    ws["A2"].alignment = Alignment(wrap_text=True)

    # --- the conventions block: this IS the feature, so it is a real range ---
    ws["A4"] = "CONVENTIONS"
    ws["A4"].font = bold
    conventions = [
        ("Pay Accrual On Default", True),
        ("Coupon Interval", "3M"),
        ("Stub Type", "f/s"),
        ("Payment DCC", "ACT/360"),
        ("Bad Day Convention", "N"),
        ("Holidays", "NONE"),
    ]
    for i, (label, value) in enumerate(conventions, start=5):
        ws.cell(row=i, column=1, value=label)
        ws.cell(row=i, column=2, value=value)
    conv_range = f"$A$5:$B${4 + len(conventions)}"

    ws["A12"] = "MARKET"
    ws["A12"].font = bold
    # The curves are built by the add-in and handed back as handles, so these
    # two cells are formulas, not constants.
    ws["A13"] = "Discount Curve"
    ws["B13"] = "FILL IN: a handle from IRZeroCurveBuild"
    ws["A14"] = "Spread Curve"
    ws["B14"] = "FILL IN: a handle from CleanSpreadCurveBuild"
    ws["A15"] = "Recovery Rate"
    ws["B15"] = 0.4
    market_range = "$A$13:$B$15"

    ws["A17"] = (
        "NOTE: the two curve handles above must come from the curve-building "
        "functions, which arrive with artifact #4. Until then the rows below "
        "will report the handle error, which is itself the correct outcome to "
        "record -- it proves the add-in loaded, registered, dispatched, and "
        "returned a readable message rather than #VALUE!."
    )
    ws["A17"].alignment = Alignment(wrap_text=True)

    # --- one row per case ---
    header_row = 19
    headers = ["Case", "Today", "Start", "End", "Coupon", "Clean",
               "CdsPrice (16 args)", "CDS.Price (5 args)", "Expected (C++)", "Verdict"]
    for col, text in enumerate(headers, start=1):
        cell = ws.cell(row=header_row, column=col, value=text)
        cell.font = bold

    for i, (case, expected) in enumerate(zip(CASES, values)):
        r = header_row + 1 + i
        ws.cell(row=r, column=1, value=case["label"])
        ws.cell(row=r, column=2, value=serial(case["today"]))
        ws.cell(row=r, column=3, value=serial(case["start"]))
        ws.cell(row=r, column=4, value=serial(case["end"]))
        ws.cell(row=r, column=5, value=case["coupon"])
        ws.cell(row=r, column=6, value=case["clean"])

        # The 16-argument form, cell by cell, exactly as a 2009 sheet wrote it.
        legacy = (
            f"=CdsPrice(B{r},B{r},B{r},C{r},D{r},E{r},"
            f"$B$5,$B$6,$B$7,$B$8,$B$9,$B$10,$B$13,$B$14,$B$15,F{r})"
        )
        ws.cell(row=r, column=7, value=legacy)

        # The grouped form. The valuation and trade blocks are built inline
        # from this row's cells, so the sheet stays one row per trade.
        grouped = f"=CDS.Price(valuation_{r},trade_{r},{conv_range},{market_range},F{r})"
        # Named inline ranges are not worth the complexity for three rows, so
        # the grouped call reads the same per-row blocks written out below.
        ws.cell(row=r, column=8, value=grouped)

        ws.cell(row=r, column=9, value=float(expected) if "ERROR" not in expected else expected)
        verdict = (
            f'=IF(ISNUMBER(G{r}),IF(ABS(G{r}-I{r})<0.000001,"PASS",'
            f'"FAIL by "&TEXT(G{r}-I{r},"0.00E+00")),"NOT A NUMBER: "&G{r})'
        )
        ws.cell(row=r, column=10, value=verdict)

    # Per-row valuation and trade blocks for the grouped form.
    block_start = header_row + 2 + len(CASES)
    ws.cell(row=block_start, column=1, value="PER-ROW BLOCKS for CDS.Price").font = bold
    row = block_start + 1
    for i, case in enumerate(CASES):
        case_row = header_row + 1 + i
        ws.cell(row=row, column=1, value=f"valuation_{case_row}")
        for j, label in enumerate(["Today", "Cash Settle Date", "Step In Date"]):
            ws.cell(row=row + j, column=2, value=label)
            ws.cell(row=row + j, column=3, value=f"=B{case_row}")
        ws.cell(row=row, column=5, value=f"trade_{case_row}")
        for j, (label, col) in enumerate(
            [("Start Date", "C"), ("End Date", "D"), ("Coupon Rate", "E")]
        ):
            ws.cell(row=row + j, column=6, value=label)
            ws.cell(row=row + j, column=7, value=f"={col}{case_row}")
        row += 4

    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["B"].width = 18
    for col in "GHIJ":
        ws.column_dimensions[col].width = 22

    OUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUT)
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  {len(CASES)} cases, expected values computed from the library:")
    for case, v in zip(CASES, values):
        print(f"    {case['label']:<24} {v}")
    print("\nNext: build cdsmodel.xll on Windows, load it, open this workbook,")
    print("and record the Verdict column in specs/reasoning/C8.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
